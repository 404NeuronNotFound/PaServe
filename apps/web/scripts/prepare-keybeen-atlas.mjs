import sharp from "sharp";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

// Register complete generated frames to a shared foot baseline. Never composite body parts.
const directory = resolve("public/images/keybeen");
const input = resolve(directory, "keybeen-animation-source.png");
const columns = [0, 235, 493, 735, 934, 1145];
const rows = [0, 352, 692, 1034, 1374];
const poses = ["wave", "left", "right", "think", "done"];
const cellWidth = 320, cellHeight = 384, baseline = 360, bodyHeight = 336;
const source = await readFile(input);
const metadata = await sharp(source).metadata();
if (metadata.width !== 1145 || metadata.height !== 1374 || !metadata.hasAlpha) throw new Error("Unexpected Keybeen source atlas");
const composites = [];
const bounds = Object.fromEntries(poses.map((pose) => [pose, { min: cellWidth, max: 0 }]));
for (let column = 0; column < poses.length; column++) {
  for (let row = 0; row < 4; row++) {
    const region = { left: columns[column], top: rows[row], width: columns[column + 1] - columns[column], height: rows[row + 1] - rows[row] };
    const { data, info } = await sharp(source).extract(region).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
    let minX = info.width, minY = info.height, maxX = 0, maxY = 0;
    for (let y = 0; y < info.height; y++) for (let x = 0; x < info.width; x++) {
      if (data[(y * info.width + x) * 4 + 3] < 32) continue;
      minX = Math.min(minX, x); minY = Math.min(minY, y); maxX = Math.max(maxX, x); maxY = Math.max(maxY, y);
    }
    let footLeft = info.width, footRight = 0;
    for (let y = Math.floor(minY + (maxY - minY) * 0.82); y <= maxY; y++) for (let x = minX; x <= maxX; x++) {
      if (data[(y * info.width + x) * 4 + 3] < 32) continue;
      footLeft = Math.min(footLeft, x); footRight = Math.max(footRight, x);
    }
    const scale = bodyHeight / (maxY - minY + 1);
    const width = Math.round((maxX - minX + 1) * scale);
    const anchor = ((footLeft + footRight) / 2 - minX) * scale;
    const left = Math.round(cellWidth / 2 - anchor), top = baseline - bodyHeight;
    if (left < 8 || left + width > cellWidth - 8) throw new Error(`Frame padding too small: ${poses[column]} row ${row}`);
    const frame = await sharp(source).extract({ left: region.left + minX, top: region.top + minY, width: maxX - minX + 1, height: maxY - minY + 1 }).resize(width, bodyHeight, { kernel: "nearest" }).png().toBuffer();
    composites.push({ input: frame, left: column * cellWidth + left, top: row * cellHeight + top });
    bounds[poses[column]].min = Math.min(bounds[poses[column]].min, left);
    bounds[poses[column]].max = Math.max(bounds[poses[column]].max, left + width);
  }
}
const width = cellWidth * 5, height = cellHeight * 4;
const pixels = await sharp({ create: { width, height, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } } }).composite(composites).raw().toBuffer();
// Canonical transparent RGB avoids encoder/display artefacts without changing visible alpha.
for (let offset = 0; offset < pixels.length; offset += 4) if (pixels[offset + 3] === 0) pixels.fill(0, offset, offset + 3);
await sharp(pixels, { raw: { width, height, channels: 4 } }).png({ compressionLevel: 9 }).toFile(resolve(directory, "keybeen-animated.png"));
const frames = Object.fromEntries(poses.map((pose, index) => [pose, { x: index * cellWidth + bounds[pose].min - 8, width: bounds[pose].max - bounds[pose].min + 16 }]));
await writeFile(resolve("src/features/walkthrough/keybeen-atlas.ts"), `// Generated by scripts/prepare-keybeen-atlas.mjs; whole-frame atlas, no face/limb overlays.\nexport const KEYBEEN_ATLAS = ${JSON.stringify({ width, height, frameHeight: cellHeight, frames }, null, 2)} as const;\n`);
console.log(JSON.stringify({ width, height, frames, framesPrepared: composites.length }));
